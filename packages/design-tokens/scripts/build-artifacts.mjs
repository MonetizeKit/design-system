// Emits the non-JS build artifacts (CSS + JSON) from the compiled token resolver.
// Runs after `tsup` (which produces dist/index.js). See package.json "build".
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const distDir = resolve(here, "../dist");

const {
  BRAND,
  PALETTES,
  PALETTE_NAMES,
  resolveTokens,
  resolveBrand,
  brandCssVars,
  semanticCssVars,
  onColorCssVars,
  mkContractVars,
  cssVarsToDeclarations,
  paletteModeSelector,
} = await import(resolve(distDir, "index.js"));

const AUTOGEN = "/* AUTO-GENERATED by scripts/build-artifacts.mjs — do not edit by hand. */";

/**
 * tokens.css — the brand default in `:root` (light) + `[data-theme="dark"]` (inverted neutrals +
 * dimmed `shade`), the fixed `.on-color` light-island neutrals, and every non-default palette in
 * both modes. Brand ramp/structure vars are mode-aware, so they are emitted in both the `:root`
 * and `[data-theme="dark"]` default blocks.
 */
function buildTokensCss() {
  const blocks = [];

  // :root — light brand ramp/structure (palette-independent) + default-light semantics.
  const rootLight = resolveTokens({ palette: "default", mode: "light" });
  blocks.push(
    `:root {\n${cssVarsToDeclarations({ ...brandCssVars(rootLight.brand), ...semanticCssVars(rootLight.semantic) })}\n}`,
  );

  // [data-theme="dark"], .dark — dark brand ramp (inverted neutrals + dimmed shade) + default-dark
  // semantics, emitted under both the attribute and the class alias (see paletteModeSelector).
  const rootDark = resolveTokens({ palette: "default", mode: "dark" });
  blocks.push(
    `${paletteModeSelector("default", "dark")} {\n${cssVarsToDeclarations({ ...brandCssVars(rootDark.brand), ...semanticCssVars(rootDark.semantic) })}\n}`,
  );

  // .on-color — fixed light-island neutrals + text color (never inverts, both modes).
  const onColorVars = onColorCssVars(rootLight.onColor);
  const onColorBody = `${cssVarsToDeclarations(onColorVars)}\n  color: ${rootLight.onColor.text};`;
  blocks.push(`.on-color {\n${onColorBody}\n}`);

  // Non-default palettes, light + dark.
  for (const mode of ["light", "dark"]) {
    for (const name of PALETTE_NAMES) {
      if (name === "default") continue; // default handled above in both modes
      const resolved = resolveTokens({ palette: name, mode });
      const selector = paletteModeSelector(name, mode);
      blocks.push(`${selector} {\n${cssVarsToDeclarations(semanticCssVars(resolved.semantic))}\n}`);
    }
  }

  return `${AUTOGEN}\n\n${blocks.join("\n\n")}\n`;
}

/** theme.css — Tailwind v4 @theme inline mapping utility names to the token custom properties. */
function buildThemeCss() {
  const semanticNames = Object.keys(resolveTokens({ palette: "default", mode: "light" }).semantic);
  const lines = [];
  lines.push('  --font-sans: var(--mk-font-sans);');
  lines.push('  --font-mono: var(--mk-font-mono);');
  lines.push('  --radius: var(--mk-radius);');
  for (const name of semanticNames) {
    lines.push(`  --color-${name}: var(--${name});`);
  }
  for (const name of Object.keys(BRAND.colors)) {
    lines.push(`  --color-mk-${name}: var(--mk-${name});`);
  }
  lines.push('  --shadow-mk-sm: var(--mk-shadow-sm);');
  lines.push('  --shadow-mk-md: var(--mk-shadow-md);');
  lines.push('  --shadow-mk-lg: var(--mk-shadow-lg);');
  return `${AUTOGEN}\n\n@theme inline {\n${lines.join("\n")}\n}\n`;
}

/** mk-tokens.css — the SDK (@monetizekit/react) --mk-* appearance contract, brand default. */
function buildMkTokensCss() {
  const light = mkContractVars(resolveTokens({ palette: "default", mode: "light" }));
  const dark = mkContractVars(resolveTokens({ palette: "default", mode: "dark" }));
  return (
    `${AUTOGEN}\n\n` +
    `:root {\n${cssVarsToDeclarations(light)}\n}\n\n` +
    `.dark {\n${cssVarsToDeclarations(dark)}\n}\n`
  );
}

/** tokens.json — machine-readable export of the source data (brand + palettes + dark/on-color). */
function buildTokensJson() {
  const onColor = resolveTokens({ palette: "default", mode: "light" }).onColor;
  return `${JSON.stringify(
    {
      $description:
        "MonetizeKit design tokens (Brand Direction v0.8). Mode-aware brand ramp/structure, the fixed .on-color light-island set, plus named palettes.",
      brand: BRAND,
      brandDark: resolveBrand("dark"),
      onColor,
      palettes: PALETTES,
    },
    null,
    2,
  )}\n`;
}

await mkdir(distDir, { recursive: true });
await Promise.all([
  writeFile(resolve(distDir, "tokens.css"), buildTokensCss(), "utf8"),
  writeFile(resolve(distDir, "theme.css"), buildThemeCss(), "utf8"),
  writeFile(resolve(distDir, "mk-tokens.css"), buildMkTokensCss(), "utf8"),
  writeFile(resolve(distDir, "tokens.json"), buildTokensJson(), "utf8"),
]);

console.log("design-tokens: emitted tokens.css, theme.css, mk-tokens.css, tokens.json");
